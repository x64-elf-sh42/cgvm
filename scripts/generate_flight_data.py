"""Regenerate fixed binary32 scene data; no runtime host geometry calculations."""
import math
import random
import struct
from pathlib import Path
rng = random.Random(7001)
values = [math.sin(i*2*math.pi/256) for i in range(256)]
values += [math.cos(i*2*math.pi/256) for i in range(256)]
values += [0, .5, 120, 400, 512, 384, 6, 1/1800]
for i in range(24):
    x, y, z = rng.uniform(-24,24), rng.uniform(-14,14), rng.uniform(10,90)
    scale = rng.uniform(1,2.8)
    yaw, pitch = rng.uniform(0,2*math.pi), rng.uniform(0,2*math.pi)
    for vx,vy,vz in [(0,1.2,0),(-1,-.8,-.8),(1,-.8,-.8),(0,-.8,1.2)]:
        vx, vz = vx*math.cos(yaw)+vz*math.sin(yaw), vz*math.cos(yaw)-vx*math.sin(yaw)
        vy, vz = vy*math.cos(pitch)-vz*math.sin(pitch), vz*math.cos(pitch)+vy*math.sin(pitch)
        values.extend((x+vx*scale,y+vy*scale,z+vz*scale))
# Vehicle is fixed in the camera's chase frame, below the center of view.
values += [0,-.7,7, -.55,-1.2,5.5, .55,-1.2,5.5, 0,-.8,5.2]
b = struct.pack('<'+'f'*len(values), *values)
Path('src/programs/flight_data.h').write_text(
    '/* Generated by scripts/generate_flight_data.py; seed 7001. */\n'
    'static uint8_t flight_data[]={\n'+''.join(
        ','.join(str(x) for x in b[i:i+24])+',\n' for i in range(0,len(b),24))+'};\n')
