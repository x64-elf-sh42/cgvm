"""Generate static meshes/materials, with normals and light directions for guest shading."""
import math, struct
from pathlib import Path
values=[1000000,0.32,0.68,0,1]
faces=[]
groups=[]
# center xyz, exclusion radius squared, LOD threshold squared.
values += [-80,20,220,68*68,200*200, 220,100,550,108*108,0]
def point(lat,lon,rows,cols):
    a=math.pi*lat/rows; b=2*math.pi*lon/cols
    return (math.sin(a)*math.cos(b),math.cos(a),math.sin(a)*math.sin(b))
def normal(v):
    length=math.sqrt(sum(x*x for x in v)); return tuple(x/length for x in v)
for body,center,radius,rows,cols,lod in [(0,(-80,20,220),60,5,10,0),(0,(-80,20,220),60,7,14,1),(1,(220,100,550),100,6,12,2)]:
    start=len(faces)
    for lat in range(rows):
        for lon in range(cols):
            a,b,c,d=point(lat,lon,rows,cols),point(lat+1,lon,rows,cols),point(lat+1,lon+1,rows,cols),point(lat,lon+1,rows,cols)
            tris=[]
            if lat: tris.append((a,b,d))
            if lat<rows-1: tris.append((b,c,d))
            for tri in tris:
                centroid=tuple(sum(v[k] for v in tri)/3 for k in range(3))
                u=tuple(tri[1][k]-tri[0][k] for k in range(3))
                v=tuple(tri[2][k]-tri[0][k] for k in range(3))
                n=normal((u[1]*v[2]-u[2]*v[1],u[2]*v[0]-u[0]*v[2],u[0]*v[1]-u[1]*v[0]))
                if sum(n[k]*centroid[k] for k in range(3))<0: n=tuple(-x for x in n)
                world=[tuple(center[k]+radius*v[k] for k in range(3)) for v in tri]
                light=normal(tuple((220,100,550)[k]-(center[k]+radius*centroid[k]) for k in range(3))) if body==0 else (0,0,1)
                color=(48,114,210)
                if centroid[1]>.72: color=(196,225,236)
                elif math.sin(centroid[0]*8+centroid[2]*4)+math.cos(centroid[1]*9)>0.45: color=(42,151,94)
                if body: color=(255,125+int(70*(.5+.5*math.sin(lon*2+lat*4))),24)
                address=16384+len(values)*4
                for v in world: values.extend(v)
                values.extend(n);values.extend(light)
                faces.append((address,*color,body))
    groups.append((start,len(faces),lod))
b=struct.pack('<'+'f'*len(values),*values)
Path('src/programs/solid_data.h').write_text('/* Generated by scripts/generate_solids.py. */\nstatic const uint8_t solid_data[]={\n'+''.join(','.join(map(str,b[i:i+24]))+',\n' for i in range(0,len(b),24))+'};\nstatic const unsigned solid_faces[][5]={\n'+''.join('{'+','.join(map(str,f))+'},\n' for f in faces)+'};\n')

with Path('src/programs/solid_data.h').open('a') as f:
    f.write('static const unsigned solid_groups[][3]={'+','.join('{'+','.join(map(str,g))+'}' for g in groups)+'};\n')
