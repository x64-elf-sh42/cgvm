#include "vm/machine.h"
#include <assert.h>
#include <math.h>
#include <stdio.h>
#include <stdlib.h>
static machine_t *m;
static void load(insn_t *code, size_t n) {
  prog_t p={.code=code,.codelen=n};
  assert(machine_load(m,&p));
}
int main(void) {
  m=malloc(sizeof(*m)); assert(m);
  insn_t arithmetic[]={MOV_RI(5,9),MOV_RI(6,3),ENC_RR(OP_DIV_RR,5,6),
    SUB_RI(5,4),ADD_RI(5,1),EXIT()};
  load(arithmetic,6);
  assert(cpu_step(m,0).executed==0 && m->regs[4]==0);
  cpu_result_t r=cpu_step(m,1);
  assert(r.status==CPU_BUDGET && r.executed==1 && m->regs[5]==9 && m->regs[4]==1);
  r=cpu_step(m,10);
  assert(r.status==CPU_HALT && r.executed==5 && m->regs[5]==0);
  assert(cpu_step(m,10).executed==0);
  insn_t branch[]={MOV_RI(5,0),ADD_RI(5,1),CMP_RI(5,3),JL(1),EXIT()};
  load(branch,5); r=cpu_step(m,20);
  assert(r.status==CPU_HALT && r.executed==11 && m->regs[5]==3);
  insn_t mem[]={MOV_RI(5,0x123),ENC_RI(OP_MOV_RM,5,0xfffff),MOV_MR(6,0xfffff),EXIT()};
  load(mem,4); assert(cpu_step(m,4).status==CPU_HALT && m->regs[6]==0x23);
  insn_t yield[]={ENC_OP(OP_YIELD),EXIT()};
  load(yield,2); r=cpu_step(m,1);
  assert(r.status==CPU_YIELD && r.executed==1 && m->regs[4]==1);
  assert(cpu_step(m,1).status==CPU_HALT);
  insn_t div[]={MOV_RI(5,9),ENC_RR(OP_DIV_RR,5,6)};
  load(div,2); r=cpu_step(m,9);
  assert(r.status==CPU_FAULT && r.executed==1 && m->fault==FAULT_DIV_ZERO);
  assert(m->regs[5]==9 && m->fault_pc==1 && cpu_step(m,1).executed==0);
  insn_t bad[]={0xff000000}; load(bad,1);
  assert(cpu_step(m,1).status==CPU_FAULT && m->fault==FAULT_OPCODE);
  insn_t pcwrite[]={MOV_RI(4,0)}; load(pcwrite,1);
  assert(cpu_step(m,1).status==CPU_FAULT && m->fault==FAULT_PC_WRITE);
  insn_t fetch[]={JMP(9)}; load(fetch,1); r=cpu_step(m,2);
  assert(r.executed==1 && m->fault==FAULT_FETCH && m->fault_pc==9);
  insn_t fp[]={ENC_RR(OP_FCMP_RR,1,2),EXIT()};
  load(fp,2); m->fpregs[1]=1; m->fpregs[2]=2;
  cpu_step(m,2); assert(m->flags==0xa000);
  load(fp,2); m->fpregs[1]=NAN; cpu_step(m,2); assert(m->flags==0x8000);
  insn_t readpc[]={MOV_RI(5,0),ENC_RR(OP_MOV_RR,5,4),EXIT()};
  load(readpc,3); cpu_step(m,3); assert(m->regs[5]==1);
  prog_t invalid={.code=readpc,.codelen=CODE_SIZE+1};
  assert(!machine_load(m,&invalid) && m->state==CPU_HALT);
  invalid=(prog_t){.code=readpc,.codelen=3,.datalen=1};
  assert(!machine_load(m,&invalid));
  insn_t gfx[]={ENC_OP(OP_FB_SWAP)}; load(gfx,1);
  assert(cpu_step(m,1).status==CPU_FAULT && m->fault==FAULT_DEVICE);
  machine_pixel_t a[4]={0},b[4]={0};
  insn_t draw[]={ENC_I24(OP_FB_CLEAR,0x123456),ENC_OP(OP_FB_SWAP),EXIT()};
  load(draw,3); m->fb=a;m->fb2=b;m->width=2;m->height=2;
  assert(cpu_step(m,3).status==CPU_HALT && b[3].red==0x12 && b[3].blue==0x56);
  machine_reset(m);
  uint32_t value;
  assert(bus_write(m,4,4,0x12345678));
  assert(bus_read(m,5,1,&value) && value==0x56);
  assert(bus_read(m,6,2,&value) && value==0x1234);
  assert(!bus_write(m,3,4,0));
  assert(!bus_write(m,0xffffffff,4,0));
  assert(!bus_read(m,DATA_SIZE-1,2,&value));
  assert(!bus_write(m,GPU_BASE+GPU_WIDTH,4,1));
  assert(!bus_read(m,GPU_BASE,1,&value));
  assert(bus_write(m,VIDEO_BASE,1,0x12));
  assert(bus_write(m,GPU_BASE+GPU_COMMAND,4,GPU_PRESENT));
  assert(bus_write(m,VIDEO_BASE,1,0x99));
  assert(bus_write(m,GPU_BASE+GPU_COMMAND,4,GPU_PRESENT) && m->gpu_error);
  machine_advance(m,FRAME_TICKS-1); assert(m->frames==0);
  machine_advance(m,1);
  assert(m->frames==1 && m->published[0].red==0x12 && m->frame_event);
  assert(bus_write(m,GPU_BASE+GPU_STATUS,4,6) && !m->frame_event && !m->gpu_error);
  assert(!bus_write(m,GPU_BASE+GPU_COMMAND,4,99));
  insn_t bus[]={ENC_RI(OP_LUI,5,GPU_BASE>>12),ENC_RR(OP_LOAD32,6,5),
    MOV_RI(7,16),ENC_RR(OP_STORE16,6,7),ENC_RR(OP_LOAD16,8,7),EXIT()};
  load(bus,6); assert(cpu_step(m,6).status==CPU_HALT && m->regs[8]==VIDEO_WIDTH);
  insn_t badbus[]={MOV_RI(5,1),ENC_RR(OP_LOAD32,6,5)};
  load(badbus,2); r=cpu_step(m,2);
  assert(r.status==CPU_FAULT && r.executed==1 && m->fault==FAULT_BUS && m->fault_address==1);
  insn_t wait[]={ENC_OP(OP_WAIT_FRAME),EXIT()};
  load(wait,2);
  assert(bus_write(m,GPU_BASE+GPU_COMMAND,4,GPU_PRESENT));
  assert(machine_step(m,10).status==CPU_WAIT && m->ticks==1);
  assert(machine_step(m,0).status==CPU_WAIT && m->ticks==1);
  assert(machine_step(m,10).status==CPU_HALT && m->ticks==FRAME_TICKS+1 && m->frames==1);
  load(wait,2); m->frame_event=true;
  assert(machine_step(m,10).status==CPU_BUDGET && !m->frame_event);
  assert(machine_step(m,1).status==CPU_HALT);
  machine_reset(m);
  assert(bus_read(m,INPUT_BASE,4,&value) && value==0);
  machine_key(m,KEY_UP,true); machine_key(m,KEY_UP,true);
  machine_key(m,KEY_UP,false);
  assert(bus_read(m,INPUT_BASE+INPUT_HELD,4,&value) && value==0);
  assert(bus_read(m,INPUT_BASE+INPUT_PRESSED,4,&value) && value==1);
  assert(bus_read(m,INPUT_BASE+INPUT_RELEASED,4,&value) && value==1);
  assert(!bus_write(m,INPUT_BASE+INPUT_ACK,4,4) && m->pressed[KEY_UP]);
  assert(bus_write(m,INPUT_BASE+INPUT_ACK,4,3));
  assert(!m->pressed[KEY_UP] && !m->released[KEY_UP]);
  assert(!bus_write(m,INPUT_BASE,4,1));
  assert(!bus_read(m,INPUT_BASE+INPUT_ACK,4,&value));
  assert(!bus_read(m,INPUT_BASE+0x80,4,&value));
  assert(!bus_read(m,INPUT_BASE,1,&value));
  machine_key(m,KEY_RIGHT,true); machine_release_keys(m);
  assert(!m->keys[KEY_RIGHT] && m->released[KEY_RIGHT]);
  insn_t fs[]={ENC_RR(OP_FSTORE32,1,5),ENC_RR(OP_FLOAD32,2,5),EXIT()};
  load(fs,3); m->regs[5]=64; m->fpregs[1]=-1.25;
  assert(cpu_step(m,3).status==CPU_HALT && m->fpregs[2]==-1.25);
  load(fs,3); m->regs[5]=65; m->fpregs[1]=1;
  assert(cpu_step(m,3).status==CPU_FAULT && m->fault==FAULT_BUS && m->data[65]==0);
  load(fs,3); m->fpregs[1]=NAN;
  assert(cpu_step(m,3).status==CPU_FAULT && m->fault==FAULT_CONVERSION);
  insn_t doubles[]={ENC_RR(OP_FSTORE64,1,5),ENC_RR(OP_FLOAD64,2,5),EXIT()};
  load(doubles,3);m->regs[5]=128;m->fpregs[1]=4500000000.0001;
  assert(cpu_step(m,3).status==CPU_HALT && m->fpregs[2]==m->fpregs[1]);
  load(doubles,3);m->regs[5]=DATA_SIZE-4;
  assert(cpu_step(m,3).status==CPU_FAULT && m->fault==FAULT_BUS);
  machine_reset(m);machine_key(m,KEY_T,true);
  assert(bus_read(m,INPUT_BASE+0x100+INPUT_PRESSED,4,&value)&&value==1);
  assert(bus_write(m,INPUT_BASE+0x100+INPUT_ACK,4,1)&&!m->pressed[KEY_T]);
  machine_reset(m);
  assert(bus_read(m,CLOCK_BASE,4,&value)&&value==0);
  machine_advance(m,UINT32_MAX);
  assert(bus_read(m,CLOCK_BASE,4,&value)&&value==UINT32_MAX);
  machine_advance(m,2);
  assert(bus_read(m,CLOCK_BASE,4,&value)&&value==1);
  assert(!bus_read(m,CLOCK_BASE,1,&value));
  assert(!bus_read(m,CLOCK_BASE+4,4,&value));
  assert(!bus_write(m,CLOCK_BASE,4,1));
  free(m); puts("CPU conformance tests passed");
}
